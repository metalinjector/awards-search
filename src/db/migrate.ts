import path from "node:path";
import { migrate } from "drizzle-orm/node-postgres/migrator";
import { errorText, log } from "@/lib/log";
import { db, pool } from "./index";

const sleep = (ms: number) => new Promise((r) => setTimeout(r, ms));

/** Wait until PostgreSQL accepts connections (it may still be starting) */
async function waitForDatabase(attempts = 60): Promise<void> {
  for (let i = 1; ; i++) {
    try {
      await pool.query("select 1");
      return;
    } catch (err) {
      if (i >= attempts) throw err;
      if (i === 1) log.info("db", "waiting for PostgreSQL…");
      await sleep(1000);
    }
  }
}

/**
 * Apply pending SQL migrations from ./drizzle (generated by `npm run db:generate`).
 * Runs once on server start; applied migrations are tracked by drizzle.
 */
export async function runMigrations(): Promise<void> {
  try {
    await waitForDatabase();
    await migrate(db, { migrationsFolder: path.join(process.cwd(), "drizzle") });
    log.info("db", "schema is up to date");
  } catch (err) {
    // Serving requests against a wrong schema would only produce confusing
    // errors — fail fast and let the container restart policy retry.
    log.error("db", "migration failed", { error: errorText(err) });
    process.exit(1);
  }
}
